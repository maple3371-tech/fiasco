/** 후기 표에서 결말을 찾습니다. color 는 "black" | "white" | "tie" */
export function aftermathFor(color, value) {
  if (!color || color === "tie" || value === 0) return { ...ZERO, label: "0" };
  const table = color === "black" ? AFTERMATH_BLACK : AFTERMATH_WHITE;
  const hit = table.find(r => value >= r.min && value <= r.max) || table[table.length - 1];
  const name = color === "black" ? "검은색" : "흰색";
  const label = hit.min === hit.max ? `${name} ${hit.min}`
    : hit.max > 900 ? `${name} ${hit.min} 이상` : `${name} ${hit.min}~${hit.max}`;
  return { ...hit, label };
}

